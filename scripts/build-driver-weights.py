"""Build smooth driver arm ownership on the original uploaded mesh.

Run: python scripts/build-driver-weights.py
Requires NumPy and SciPy. UV seam copies share a weight; no runtime solver.
"""
import base64
import gzip
import json
import struct
from pathlib import Path
import numpy as np
from scipy.sparse import coo_matrix, diags
from scipy.sparse.csgraph import connected_components
from scipy.sparse.linalg import spsolve

root = Path(__file__).resolve().parents[1]
manifest = json.loads((root / 'models/arena-original-honk-v171.json').read_text())
blob = gzip.decompress(b''.join((root / 'models' / name).read_bytes() for name in manifest['parts']))
json_size = struct.unpack_from('<I', blob, 12)[0]
gltf = json.loads(blob[20:20 + json_size])
buffer = blob[28 + json_size:]
primitive = gltf['meshes'][0]['primitives'][0]
def accessor(index, components):
    a = gltf['accessors'][index]
    view = gltf['bufferViews'][a['bufferView']]
    offset = view.get('byteOffset', 0) + a.get('byteOffset', 0)
    dtype = {5123: '<u2', 5125: '<u4', 5126: '<f4'}[a['componentType']]
    return np.frombuffer(buffer, dtype=dtype, offset=offset, count=a['count'] * components).reshape(-1, components)
p = accessor(primitive['attributes']['POSITION'], 3).copy()
f = accessor(primitive['indices'], 1).reshape(-1, 3)
lo, hi = p.min(0).astype(float), p.max(0).astype(float)
origin = (lo + hi) / 2
origin[1] = lo[1]
p = (p.astype(float) - origin).astype(np.float32)
p = (p.astype(float) / (hi[1] - lo[1])).astype(np.float32)
# Weld only for the solve: keep every original vertex, triangle and UV intact.
u, reverse = np.unique(np.round(p, 5), axis=0, return_inverse=True)
j = reverse[f]
edges = np.vstack([j[:, [0, 1]], j[:, [1, 2]], j[:, [2, 0]]])
edges = np.vstack([edges, edges[:, ::-1]])
a = coo_matrix((np.ones(len(edges)), (edges[:, 0], edges[:, 1])), shape=(len(u), len(u))).tocsr()
a.data[:] = 1
# Below the cuffs, the two hands are distinct connected surface branches.
low = u[:, 1] < .37
_, labels = connected_components(a[low][:, low], directed=False)
hand_ids = [labels[np.argmin(np.linalg.norm(u[low] - [side * .245, .3, -.01], axis=1))] for side in [-1, 1]]
assert hand_ids[0] != hand_ids[1]
field = np.full(len(u), -1.)
field[low] = np.isin(labels, hand_ids)
field[u[:, 1] >= .56] = 0
trunk = (u[:, 1] >= .37) & ((np.abs(u[:, 0]) < .195) | ((np.abs(u[:, 2] + .01) > .08) & (np.abs(u[:, 0]) < .22)))
field[trunk] = 0
outer_sleeve = (u[:, 1] >= .37) & (u[:, 1] < .50) & (np.abs(u[:, 0]) > .235) & (np.abs(u[:, 2] + .01) < .06)
field[outer_sleeve] = 1
unknown, known = field < 0, field >= 0
laplacian = diags(np.asarray(a.sum(1)).ravel()) - a
field[unknown] = spsolve(laplacian[unknown][:, unknown], -laplacian[unknown][:, known] @ field[known])
strength = np.clip((field[reverse] - .05) / .85, 0, 1)
strength = strength * strength * (3 - 2 * strength)
weights = np.round(strength * 65535).astype(np.uint16)
# Short repeated runs plus literal spans avoid shipping a dense numeric array.
encoded = bytearray()
start = 0
while start < len(weights):
    end = start + 1
    while end < len(weights) and weights[end] == weights[start] and end - start < 32767:
        end += 1
    if end - start >= 3:
        encoded.extend(struct.pack('<HH', 32768 | (end - start), int(weights[start])))
        start = end
        continue
    end = start
    while end < len(weights) and end - start < 32767:
        if end + 2 < len(weights) and weights[end] == weights[end + 1] == weights[end + 2]:
            break
        end += 1
    encoded.extend(struct.pack('<H', end - start))
    encoded.extend(weights[start:end].astype('<u2').tobytes())
    start = end
source = f'''// Generated by scripts/build-driver-weights.py for arena-original-honk-v171.
// Harmonic surface weights keep the complete palms and sleeves on their arms.
const encoded='{base64.b64encode(encoded).decode()}';
let weights;
export function loadDriverArmWeights(vertexCount){{
 if(vertexCount!=={len(weights)})throw Error('Driver skin does not match the uploaded HONK mesh');
 if(weights)return weights;
 const bytes=Uint8Array.from(atob(encoded),c=>c.charCodeAt(0)),view=new DataView(bytes.buffer);
 weights=new Uint16Array(vertexCount);let input=0,output=0;
 while(input<bytes.length){{const tag=view.getUint16(input,true),count=tag&32767;input+=2;if(tag&32768){{weights.fill(view.getUint16(input,true),output,output+count);input+=2;output+=count}}else for(let n=0;n<count;n++){{weights[output++]=view.getUint16(input,true);input+=2}}}}
 if(output!==vertexCount)throw Error('Incomplete driver skin');
 return weights;
}}
'''
path = root / 'original-honk-driver-weights.js'
path.write_text(source)
print(path.name, path.stat().st_size, 'bytes')
